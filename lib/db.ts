// Two drivers behind one tiny async interface:
//  - DATABASE_URL set (Supabase / any Postgres) -> postgres.js. Required on Vercel.
//  - otherwise -> local SQLite file via better-sqlite3 (zero setup for local use).
// SQL is written once with `?` placeholders; the Postgres driver rewrites them to $1..$n.
import { seed } from "./seed";

export const WS = process.env.SETLO_WORKSPACE_ID || "ws_demo";
export const now = () => new Date().toISOString();

type Params = unknown[];
export interface Db {
  dialect: "sqlite" | "pg";
  all<T = Record<string, unknown>>(sql: string, params?: Params): Promise<T[]>;
  get<T = Record<string, unknown>>(sql: string, params?: Params): Promise<T | undefined>;
  run(sql: string, params?: Params): Promise<void>;
  /** INSERT ... and return the new row id. */
  insert(sql: string, params?: Params): Promise<number>;
  exec(sql: string): Promise<void>;
}

function schema(d: Db["dialect"]) {
  const ID = d === "pg" ? "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : "INTEGER PRIMARY KEY AUTOINCREMENT";
  return `
CREATE TABLE IF NOT EXISTS workspaces (
  id TEXT PRIMARY KEY, workspace_id TEXT NOT NULL, name TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS leads (
  id ${ID},
  workspace_id TEXT NOT NULL,
  first_name TEXT NOT NULL DEFAULT '', last_name TEXT NOT NULL DEFAULT '',
  phone TEXT NOT NULL DEFAULT '', email TEXT NOT NULL DEFAULT '',
  stage TEXT NOT NULL DEFAULT 'text_blasted',
  cash_value DOUBLE PRECISION NOT NULL DEFAULT 0,
  next_follow_up TEXT,
  source_tool TEXT NOT NULL DEFAULT '',
  ghl_contact_id TEXT,
  created_at TEXT NOT NULL, updated_at TEXT NOT NULL, stage_changed_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS leads_ws ON leads(workspace_id, stage);
CREATE TABLE IF NOT EXISTS activities (
  id ${ID},
  workspace_id TEXT NOT NULL,
  lead_id INTEGER NOT NULL REFERENCES leads(id) ON DELETE CASCADE,
  type TEXT NOT NULL, body TEXT NOT NULL DEFAULT '', meta TEXT,
  created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS act_lead ON activities(workspace_id, lead_id);
CREATE TABLE IF NOT EXISTS snippets (
  id ${ID},
  workspace_id TEXT NOT NULL,
  title TEXT NOT NULL, body TEXT NOT NULL, category TEXT NOT NULL DEFAULT 'General',
  uses INTEGER NOT NULL DEFAULT 0, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS call_notes (
  id ${ID},
  workspace_id TEXT NOT NULL,
  lead_id INTEGER REFERENCES leads(id) ON DELETE SET NULL,
  transcript TEXT NOT NULL DEFAULT '', summary TEXT NOT NULL DEFAULT '',
  objections TEXT NOT NULL DEFAULT '', commitments TEXT NOT NULL DEFAULT '',
  next_step TEXT NOT NULL DEFAULT '', resources TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS settings (
  workspace_id TEXT NOT NULL, key TEXT NOT NULL, value TEXT NOT NULL,
  PRIMARY KEY (workspace_id, key)
);`;
}

async function openPg(url: string): Promise<Db> {
  const postgres = (await import("postgres")).default;
  const local = /@(localhost|127\.0\.0\.1)[:/]/.test(url) || url.includes("sslmode=disable");
  // prepare:false keeps us compatible with Supabase's transaction pooler (port 6543).
  const sql = postgres(url, { prepare: false, max: 3, idle_timeout: 20, ssl: local ? false : "require", onnotice: () => {} });
  const q = (s: string) => { let i = 0; return s.replace(/\?/g, () => `$${++i}`); };
  const run = (s: string, p: Params = []) => sql.unsafe(q(s), p as never[]);
  return {
    dialect: "pg",
    all: async (s, p) => (await run(s, p)) as never,
    get: async (s, p) => ((await run(s, p))[0] as never) ?? undefined,
    run: async (s, p) => { await run(s, p); },
    insert: async (s, p) => Number((await run(`${s} RETURNING id`, p))[0].id),
    exec: async (s) => { await sql.unsafe(s); },
  };
}

async function openSqlite(): Promise<Db> {
  const [{ default: Database }, fs, path] = await Promise.all([import("better-sqlite3"), import("node:fs"), import("node:path")]);
  const file = process.env.SETLO_DB_PATH || path.join(process.cwd(), "data", "setlo.db");
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const db = new Database(file);
  db.pragma("journal_mode = WAL");
  db.pragma("foreign_keys = ON");
  return {
    dialect: "sqlite",
    all: async (s, p = []) => db.prepare(s).all(...p) as never,
    get: async (s, p = []) => db.prepare(s).get(...p) as never,
    run: async (s, p = []) => { db.prepare(s).run(...p); },
    insert: async (s, p = []) => Number(db.prepare(s).run(...p).lastInsertRowid),
    exec: async (s) => { db.exec(s); },
  };
}

async function init(): Promise<Db> {
  const url = process.env.DATABASE_URL;
  if (!url && process.env.VERCEL) throw new Error("DATABASE_URL is not set. Add your Supabase connection string in Vercel → Settings → Environment Variables.");
  const db = url ? await openPg(url) : await openSqlite();
  await db.exec(schema(db.dialect));
  // Atomic "first boot" check, safe if two requests race on a fresh database.
  const fresh = await db.get("INSERT INTO workspaces (id,workspace_id,name,created_at) VALUES (?,?,?,?) ON CONFLICT (id) DO NOTHING RETURNING id", [WS, WS, "Demo Workspace", now()]);
  if (fresh && process.env.SETLO_SEED !== "false") await seed(db, WS);
  return db;
}

const g = globalThis as unknown as { __setloDb?: Promise<Db> };
export function getDb(): Promise<Db> {
  if (!g.__setloDb) g.__setloDb = init().catch((e) => { g.__setloDb = undefined; throw e; });
  return g.__setloDb;
}

export async function getSetting(key: string, fallback = ""): Promise<string> {
  const db = await getDb();
  const r = await db.get<{ value: string }>("SELECT value FROM settings WHERE workspace_id=? AND key=?", [WS, key]);
  return r?.value ?? fallback;
}
export async function setSetting(key: string, value: string) {
  const db = await getDb();
  await db.run("INSERT INTO settings (workspace_id,key,value) VALUES (?,?,?) ON CONFLICT (workspace_id,key) DO UPDATE SET value=excluded.value", [WS, key, value]);
}
export async function logActivity(leadId: number, type: string, body: string, meta?: unknown) {
  const db = await getDb();
  await db.run("INSERT INTO activities (workspace_id,lead_id,type,body,meta,created_at) VALUES (?,?,?,?,?,?)", [
    WS, leadId, type, body, meta === undefined ? null : JSON.stringify(meta), now(),
  ]);
}
